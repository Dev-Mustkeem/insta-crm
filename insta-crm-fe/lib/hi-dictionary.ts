const normalise = (text: string) => text.replace(/\s+/g, " ").trim();

/** Translate one string to Hindi. Returns the original text when no translation is known. */
export function toHindi(text: string): string {
  const core = normalise(text);
  if (!core) return text;
  const lead = text.match(/^\s*/)?.[0] ?? "";
  const trail = text.match(/\s*$/)?.[0] ?? "";
  const exact = HI_DICTIONARY[core];
  if (exact !== undefined) return lead + exact + trail;
  for (const [pattern, replacement] of HI_PATTERNS) {
    const match = core.match(pattern);
    if (!match) continue;
    // Captured fragments that are dictionary entries (stage names, sources…) are translated too.
    const groups = match.slice(1).map((g) => (g === undefined ? "" : toHindi(g)));
    return lead + replacement.replace(/\$(\d)/g, (_, i) => groups[Number(i) - 1] ?? "") + trail;
  }
  // Comma-joined messages (e.g. API classifier reasons): translate each segment.
  for (const separator of [" · ", ", "]) {
    if (!core.includes(separator)) continue;
    const parts = core.split(separator);
    const translated = parts.map((part) => toHindi(part));
    if (translated.some((part, i) => part !== parts[i])) return lead + translated.join(separator) + trail;
  }
  return text;
}
